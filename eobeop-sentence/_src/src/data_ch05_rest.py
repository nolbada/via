EX_COND = ('<b>일어날 수 있는 일</b>(조건 부사절)은 if절에 <b>현재시제</b>를 써요. 주절은 will 등이에요. 미래의 일이어도 if절에는 will을 쓰지 않아요.')
EX_ASIF = ('<b>as if</b>: 주절과 같은 때의 일이면 <b>과거시제</b>(be동사는 were), 주절보다 더 앞선 일이면 <b>had p.p.</b>')

