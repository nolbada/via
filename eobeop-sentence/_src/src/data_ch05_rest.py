def I(t, ans, ko, why, st=None, ex='', hard=False, **kw):
    d = dict(t=t, ans=ans, ko=ko, why=why, st=st or [], ex=ex, hard=hard)
    d.update(kw)
    return d
S_ = lambda x: ('s', '주어', x)
V_ = lambda x: ('v', '동사', x)
CL = lambda x: ('c', 'if절 동사', x)
MC = lambda x: ('c', '주절', x)
AI = lambda x: ('v', 'as if절', x)
MV = lambda x: ('v', '주절 동사', x)
TM = lambda x: ('m', '시간 단서', x)
PS = lambda x: ('c', '가능성', x)

