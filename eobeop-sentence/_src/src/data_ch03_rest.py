def I(t, ans, ko, why, st=None, ex='', hard=False, **kw):
    d = dict(t=t, ans=ans, ko=ko, why=why, st=st or [], ex=ex, hard=hard)
    d.update(kw)
    return d
S_ = lambda x: ('s', '주어', x)
M_ = lambda x: ('m', '수식어', x)
V_ = lambda x: ('v', '동사', x)
C_ = lambda x: ('c', '연결', x)
A_ = lambda x: ('s', '선행사', x)
W_ = lambda x: ('c', '관계대명사', x)

